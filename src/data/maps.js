export function getMap(regionId) {
    return Maps[regionId] || null;
}

export function getMapMeta(regionId) {
    return MapMeta[regionId] || null;
}

export function getTileAt(regionId, x, y) {
    const map = Maps[regionId];
    if (!map || y < 0 || y >= map.length || x < 0 || x >= map[0].length) {
        return 1; // Out of bounds = wall
    }
    return map[y][x];
}

